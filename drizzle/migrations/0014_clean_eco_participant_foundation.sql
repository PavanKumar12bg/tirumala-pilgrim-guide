CREATE OR REPLACE FUNCTION public.eco_review_activity(_id uuid,_status text,_plastic numeric,_saplings integer,_comments text,_expected_version integer)
RETURNS boolean LANGUAGE plpgsql SET search_path=public AS $$
DECLARE oldrow public.eco_contribution_snapshots; newrow public.eco_contribution_snapshots;
BEGIN
 IF NOT public.has_role(auth.uid(),'admin') THEN RAISE EXCEPTION 'Forbidden'; END IF;
 IF _status NOT IN ('pending','approved','rejected') OR _plastic<0 OR _plastic>1000000 OR _saplings<0 OR _saplings>1000000 OR length(_comments)>2000 THEN RAISE EXCEPTION 'Invalid review'; END IF;
 SELECT * INTO oldrow FROM public.eco_contribution_snapshots WHERE activity_id=_id FOR UPDATE;
 IF NOT FOUND OR oldrow.version<>_expected_version THEN RAISE EXCEPTION 'Activity changed; refresh before reviewing'; END IF;
 UPDATE public.eco_contribution_snapshots SET status=_status,plastic_kg=CASE WHEN _status='approved' THEN _plastic ELSE 0 END,saplings=CASE WHEN _status='approved' THEN _saplings ELSE 0 END,comments=_comments,version=version+1,reviewed_by=auth.uid(),reviewed_at=now() WHERE activity_id=_id RETURNING * INTO newrow;
 INSERT INTO public.eco_review_events(activity_id,participant_id,actor_id,previous_values,new_values,reason) VALUES(_id,oldrow.participant_id,auth.uid(),to_jsonb(oldrow),to_jsonb(newrow),_comments);
 UPDATE public.eco_submission_outbox SET sync_status='pending',updated_at=now() WHERE id=_id;
 UPDATE public.eco_cards SET status='under_review' WHERE participant_id=oldrow.participant_id AND status='generated';
 RETURN true;
END $$;
REVOKE ALL ON FUNCTION public.eco_review_activity(uuid,text,numeric,integer,text,integer) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.eco_review_activity(uuid,text,numeric,integer,text,integer) TO authenticated;
GRANT INSERT ON public.eco_review_events TO authenticated;
